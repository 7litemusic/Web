/**
 * Determine initial language:
 * 1. Saved user preference in localStorage
 * 2. If browser language is Spanish ('es'), use 'es'
 * 3. Default to 'en'
 */
function detectPreferredLanguage() {
  const saved = localStorage.getItem('7lite_lang');
  if (saved && (saved === 'en' || saved === 'es')) {
    return saved;
  }
  const browserLang = (navigator.language || navigator.userLanguage || '').toLowerCase();
  if (browserLang.startsWith('es')) {
    return 'es';
  }
  return 'en'; // Default is English
}

let currentLanguage = detectPreferredLanguage();

function applyTranslations(lang) {
  currentLanguage = lang;
  document.documentElement.lang = lang;
  localStorage.setItem('7lite_lang', lang);

  const t = translations[lang] || translations.en;

  // 1. Text / HTML elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      el.innerHTML = t[key];
    }
  });

  // 2. Placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) {
      el.placeholder = t[key];
    }
  });

  // 3. Titles / aria-labels
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    if (t[key] !== undefined) {
      el.title = t[key];
      el.setAttribute('aria-label', t[key]);
    }
  });

  // 4. Update desktop & mobile switchers
  updateSwitcherUI(lang);

  // 5. Update dropdown placeholder if not customized
  const selectedText = document.getElementById('selected-option-text');
  const projectInput = document.getElementById('contact-project-input');
  if (selectedText && (!projectInput || !projectInput.value)) {
    selectedText.textContent = t.contact_project_select;
  }

  // 6. Broadcast event for other modules
  window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang } }));
}

function updateSwitcherUI(lang) {
  // Desktop buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === lang) {
      btn.className = 'lang-btn px-2.5 py-1 rounded-md transition-all font-bold text-white bg-[#333333] shadow-sm';
      btn.setAttribute('aria-pressed', 'true');
    } else {
      btn.className = 'lang-btn px-2.5 py-1 rounded-md transition-all font-semibold text-[#888888] hover:text-white';
      btn.setAttribute('aria-pressed', 'false');
    }
  });

  // Mobile buttons
  document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === lang) {
      btn.className = 'mobile-lang-btn px-3 py-1 rounded-md transition-all font-bold text-white bg-[#333333] shadow-sm';
      btn.setAttribute('aria-pressed', 'true');
    } else {
      btn.className = 'mobile-lang-btn px-3 py-1 rounded-md transition-all font-semibold text-[#888888] hover:text-white';
      btn.setAttribute('aria-pressed', 'false');
    }
  });
}

function initLanguageEngine() {
  // Bind desktop switcher clicks
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const targetLang = btn.getAttribute('data-lang');
      if (targetLang && targetLang !== currentLanguage) {
        applyTranslations(targetLang);
      }
    });
  });

  // Bind mobile switcher clicks
  document.querySelectorAll('.mobile-lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const targetLang = btn.getAttribute('data-lang');
      if (targetLang && targetLang !== currentLanguage) {
        applyTranslations(targetLang);
      }
    });
  });

  // Apply initial detected or saved language
  applyTranslations(currentLanguage);
}

// Expose globals
window.currentLanguage = currentLanguage;
window.applyTranslations = applyTranslations;
window.initLanguageEngine = initLanguageEngine;
